"""Compute the proposed r02 source map; installed state and host identity stay unproven."""
import argparse
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from replacement_bundle import digest, encoded, write_new
from replacement_host import required_source_paths
from r3_artifacts import ROOT
from r3_guard_files import payload
from r3_install import DAEMON


def prepare(node_binary_hash, output, runtime=None):
    import re
    if not re.fullmatch('[a-f0-9]{64}', node_binary_hash):
        raise ValueError('Archive-derived Node binary hash required; execution is still unproven.')
    upstream = json.loads((ROOT / 'infra/selfhost/upstream.lock.json').read_bytes())
    lock = json.loads((ROOT / 'infra/selfhost/r3-toolchain.lock.json').read_bytes())
    generated = {name: (data, mode) for name, (data, mode) in payload().items()}
    generated['/etc/docker/daemon.json'] = (encoded(DAEMON), 0o600)
    generated['/etc/tonyai/docker-packages.txt'] = (
        ''.join(p['name'] + '=' + p['version'] + '\n' for p in lock['packages']).encode(), 0o600)
    entries = {}
    for target in sorted(required_source_paths()):
        path = Path(target)
        if target in generated:
            data, mode = generated[target]
            value, origin = digest(data), 'deterministic generated bytes'
        elif target == '/opt/tonyai-tools/node-v22.23.3-linux-x64/bin/node':
            value, mode, origin = node_binary_hash, 0o755, 'pinned archive member; caller supplied hash'
        elif target.startswith('/usr/local/lib/tonyai/'):
            source = ROOT / 'infra/scripts' / path.name
            value, mode, origin = digest(source.read_bytes()), 0o644, str(source.relative_to(ROOT))
        elif target.startswith('/opt/tonyai/supabase/'):
            name = target.removeprefix('/opt/tonyai/supabase/')
            if name in upstream['files']:
                value, origin = upstream['files'][name], 'upstream.lock.json:' + name
            else:
                source = ROOT / 'infra/selfhost' / ('images.qa.lock.json' if name == 'compose.images.json' else name)
                value, origin = digest(source.read_bytes()), str(source.relative_to(ROOT))
            mode = 0o755 if name.endswith('entrypoint.sh') else 0o644
        else:
            raise ValueError('Unmapped host source.')
        entries[target] = {'sha256': value, 'uid': 0, 'gid': 0, 'mode': oct(mode), 'origin': origin}
    files = {name: item['sha256'] for name, item in entries.items()}
    template = 'volumes/api/envoy/lds.template.yaml'
    derived = {'path': '/opt/tonyai/supabase/volumes/api/envoy/lds.qa.yaml',
               'template_sha256': upstream['files'][template],
               'sha256': None, 'uid': 0, 'gid': 0, 'mode': '0o644',
               'verification': 'replacement_host.check_source_tree exact deterministic redaction; outside contract files'}
    if runtime is not None:
        data = (Path(runtime) / template).read_bytes()
        if digest(data) != upstream['files'][template]:
            raise ValueError('Gateway template differs from the upstream pin.')
        lines = data.decode().splitlines(keepends=True)
        anchors = [i for i, line in enumerate(lines) if 'inline_string:' in line and '%REQ(X-ENVOY-ORIGINAL-PATH?:PATH)%' in line]
        if len(anchors) != 1:
            raise ValueError('Gateway template anchor differs.')
        lines[anchors[0]] = '                        inline_string: "%RESPONSE_CODE% %BYTES_RECEIVED% %BYTES_SENT% %DURATION%\\n"\n'
        derived['sha256'] = digest(''.join(lines).encode())
    report = {'format': 1, 'status': 'SOURCE_PLAN_NOT_HOST_OBSERVATION', 'files': entries,
              'proposed_contract_files': files, 'proposed_source_sha256': digest(encoded(files)),
              'derived_gateway': derived,
              'private_generated_files': 'Environment, initialization/custody journals and intrinsic keys are bound privately after approved generation; never included in this public map.',
              'installed_receipt': '/etc/tonyai/r3-installed-receipt.json',
              'receipt_binding_note': 'Bind observed receipt separately to approval/contract, avoiding a circular contract hash.',
              'excluded_entrypoints': ['selfhost_docker.sh', 'selfhost_host_guard.sh'],
              'required_execution': ['Independent SSH fingerprint and strict known-hosts verification',
                                     'Fresh control-plane/IMDS VM UUID, OS/data disk identities',
                                     'Separately approved disk format, filesystem UUIDs, fstab and real mounts',
                                     'Exact installed file hashes, uid/gid/modes and complete safe path chains',
                                     'Node binary receipt and actual absolute-path --version',
                                     'SSH validation, systemd guard wiring and container IMDS denial',
                                     'Environment custody before database and intrinsic custody before remaining services'],
              'bootstrap_status': 'NOT_READY_FOR_BOOTSTRAP_APPROVAL'}
    write_new(output, json.dumps(report, indent=2).encode())
    return report


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('node_binary_sha256')
    parser.add_argument('output')
    parser.add_argument('--runtime')
    args = parser.parse_args()
    try:
        prepare(args.node_binary_sha256, args.output, args.runtime)
        print('PASS: proposed source map computed; no host installed or approved.')
    except Exception:
        raise SystemExit('FAIL: source planning refused.')

import { describe, expect, it } from 'vitest';
import { CATEGORY_ACTIVITY_TYPES, COUNTED_STATUSES, REPORTING_PERIODS, type Category } from '@tonyai/shared-types';
import { BODY_COLUMNS, TRAILING_COLUMNS } from './report-columns';
import { EN_VOCABULARY, plainDigits, REPORT_CATALOGUES, reportVocabulary } from './report-vocabulary';

/**
 * The live report's words (LP4-03 K6): English is the identity of what the
 * writers printed before; Turkish has a word for every label and categorical
 * cell a live PDF or workbook prints; and a person's text can never become
 * markup through the trusted-markup markers.
 */

const tr = reportVocabulary('tr');
const MARK_OPEN = String.fromCharCode(1);
const MARK_CLOSE = String.fromCharCode(2);

describe('the markup markers', () => {
  it('never let a value become markup, however it is spelled', () => {
    const hostile = `${MARK_OPEN}uncalculated${MARK_CLOSE}<img src=x>`;
    const html = EN_VOCABULARY.html(
      'uncalculatedNote',
      { total: hostile, notCalculated: 'Not calculated' },
      { uncalculated: '<strong>1</strong>' },
    );
    expect(html.match(/<strong>1<\/strong>/g)).toHaveLength(1);
    expect(html).toContain('&lt;img src=x&gt;');
    expect(html).not.toContain(MARK_OPEN);
    expect(html).not.toContain(MARK_CLOSE);
  });

  it('formats ICU syntax in a value as text, never as a message', () => {
    expect(EN_VOCABULARY.text('generatedBy', { email: "{x} # 'q' <b>" })).toBe("Generated by {x} # 'q' <b>");
    expect(EN_VOCABULARY.html('generatedBy', { email: '<b>' })).toBe('Generated by &lt;b&gt;');
  });
});

describe('a stored figure in full, in either language (Codex B9 P2-1)', () => {
  it.each([
    [1.5e-21, '0.0000000000000000000015', '0,0000000000000000000015'],
    [-2.5e-7, '-0.00000025', '-0,00000025'],
    [0.44, '0.44', '0,44'],
    [1234567.125, '1234567.125', '1234567,125'],
    [1e21, '1000000000000000000000', '1000000000000000000000'],
    [1.2345e22, '12345000000000000000000', '12345000000000000000000'],
    [0, '0', '0'],
  ])('%s keeps every digit: %s / %s', (n, en, trText) => {
    expect(plainDigits(n)).toBe(en);
    expect(EN_VOCABULARY.fullFigure(n)).toBe(en);
    expect(tr.fullFigure(n)).toBe(trText);
    // The digits are the number's own: they read back to it exactly.
    expect(Number(en)).toBe(n);
  });
});

describe('the Turkish catalogue covers every word a live PDF or workbook prints', () => {
  const labels = [
    ...BODY_COLUMNS.flatMap((c) => [c.excel?.label, c.pdf?.label]),
    ...TRAILING_COLUMNS.map((c) => c.excel.label),
    // The writers' own tables and the withdrawn tables' relabelled columns.
    'tCO₂e removed', 'Withdrawn (UTC)', 'Reason', 'Withdrawn by', 'Withdrawn by (user id)', 'Scope', '% of total', 'Records',
    'Geography', 'Factor value', 'Factor unit', 'Factor', 'Methodology', 'Source', 'Version', 'Release', 'Standing', 'Record',
    'Files', 'File names',
  ].filter((l): l is string => l !== undefined);
  // Words the same in both languages.
  const SAME = new Set(['tCO₂e']);

  it.each([...new Set(labels)])('label %s', (label) => {
    expect(`label ${label}` in REPORT_CATALOGUES.tr, `missing "label ${label}"`).toBe(true);
    if (!SAME.has(label)) expect(tr.label(label)).not.toBe(label);
  });

  it('every status a live ledger prints, every reporting period, and the activity types by name', () => {
    for (const status of [...COUNTED_STATUSES, 'voided']) expect(tr.recordStatus(status), status).not.toBe(status);
    for (const period of REPORTING_PERIODS) expect(tr.reportingPeriod(period), period).not.toBe(period);
    const named = Object.entries(CATEGORY_ACTIVITY_TYPES).flatMap(([category, def]) =>
      (def?.types ?? []).map((t) => ({ category: category as Category, activityType: t.value, label: t.label })));
    for (const { category, activityType, label } of named) {
      // A refrigerant's code is its name in every language.
      if (/^R-\d/.test(label) || ['LPG', 'Fuel oil'].includes(label)) continue;
      expect(tr.activityType({ category, activityType }), `${category} ${activityType}`).not.toBe(label);
    }
  });

  it('English prints the stored words, exactly as before', () => {
    expect(EN_VOCABULARY.category('Natural Gas')).toBe('Natural Gas');
    expect(EN_VOCABULARY.period('January')).toBe('January');
    expect(EN_VOCABULARY.recordStatus('under_review')).toBe('under_review');
    expect(EN_VOCABULARY.entity({ locationId: null })).toBe('Whole company');
    expect(EN_VOCABULARY.number.format(1234.56)).toBe('1,234.6');
    expect(tr.number.format(1234.56)).toBe('1.234,6');
  });
});
